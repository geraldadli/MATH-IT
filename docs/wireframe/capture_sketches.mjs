import {createRequire} from 'node:module';
import {readFile,mkdir,writeFile,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.WIREFRAME_PLAYWRIGHT||'C:/Users/Asus/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root=path.dirname(fileURLToPath(import.meta.url));
const output=path.resolve(root,'../../output/wireframes/screens');
await mkdir(output,{recursive:true});
const list=JSON.parse(await readFile(path.join(root,'sketches/manifest.json'),'utf8'));
const browser=await chromium.launch();
const page=await browser.newPage({deviceScaleFactor:2});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
for(const s of list){
  await page.setViewportSize({width:s.width,height:s.height});
  await page.goto(new URL(`sketches/${s.id}.html`,import.meta.url).href);
  await page.evaluate(()=>document.fonts.ready);
  await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  const outside=await page.locator('svg text').evaluateAll(es=>es.filter(e=>{const b=e.getBBox();const v=e.ownerSVGElement.viewBox.baseVal;return b.x<0||b.y<0||b.x+b.width>v.width+1||b.y+b.height>v.height+1;}).map(e=>e.textContent));
  if(outside.length)throw Error(`${s.id}: text outside drawing: ${outside}`);
  const links=await page.locator('svg a').evaluateAll(es=>es.map(e=>e.getAttribute('href')));
  for(const href of links)await readFile(path.join(root,'sketches',href));
  await page.screenshot({path:path.join(output,s.id+'.png'),fullPage:true});
}
await copyFile(path.resolve(root,'../../output/pdf/Math-It-Wireframe-Proposal.pdf'),path.join(root,'proposal.pdf'));
// Check the click-through journey in the actual review workspace.
await page.setViewportSize({width:1440,height:1150});
await page.goto(new URL('index.html',import.meta.url).href);
const inside=()=>page.frameLocator('#drawing');
await inside().locator('a[aria-label="Start investigation  ->"]').click();
await inside().locator('svg[aria-label="02. Casebook / choose a unit"]').waitFor();
await inside().locator('a[aria-label="Open case  ->"]').click();
await inside().locator('svg[aria-label="04. First-use / how to move"]').waitFor();
await inside().locator('a[aria-label="Let me try"]').click();
await inside().locator('svg[aria-label="03. Case activity / clue sorting"]').waitFor();
await inside().locator('a[aria-label="Hint"]').click();
await inside().locator('svg[aria-label="05. Help / hint dialog"]').waitFor();
await inside().locator('body').click({position:{x:5,y:5}});
await page.keyboard.press('Escape');
await inside().locator('svg[aria-label="03. Case activity / clue sorting"]').waitFor();
await inside().locator('a[aria-label="Check"]').click();
await inside().locator('svg[aria-label="07. Success / case solved"]').waitFor();
await page.locator('[data-screen="welcome"]').click();
await page.locator('#mobile').click();
await inside().locator('svg[aria-label="M1. Welcome / mobile"]').waitFor();
await inside().locator('a[aria-label="Start investigation  ->"]').click();
await inside().locator('svg[aria-label="M2. Casebook / mobile"]').waitFor();
if(errors.length)throw Error(errors.join('; '));
await writeFile(path.join(output,'verification.json'),JSON.stringify({status:'passed',screens:list.length,brokenLinks:0,textOutsideDrawings:0,browserErrors:errors,flow:['welcome','casebook','demo','clues','hint','clues','success'],mobileFlow:['welcome-mobile','casebook-mobile']},null,2));
await browser.close();
console.log(JSON.stringify({status:'passed',screens:list.length,output}));
